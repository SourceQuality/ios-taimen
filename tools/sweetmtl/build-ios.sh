#!/bin/bash
# Build the Metal stack's iOS 16 arm64 binaries (docs/taimen-metal-plan.md 4.4): the test tools mtlbridgetest (the
# bridge's self-test) and mtlabitest (the frontend's object ABI), each flame's bridge + sweetmtl-runtime + the
# metal2vulkan translator (Rust, aarch64-apple-ios), the Gallium shim and tools/sweetgl/sweet_drm.c (the iPhoneOS
# clang) and Mesa freedreno a5xx, signed ad hoc. macOS with Xcode's iPhoneOS SDK; the CI job is
# .github/workflows/sweetmtl.yml.
#
#   tools/sweetmtl/build-ios.sh
#
# Before it (the CI job's steps), Mesa for iOS in trees of its own, not sweetgl's:
#   export MESA_SRC=$PWD/research/mesa-mtl MESA_BUILD=$PWD/research/mesa-ios-mtl
#   sh tools/sweetgl/mesa-fetch.sh                  # the pin + tools/sweetgl/mesa.patch
#   (cd "$MESA_SRC" && patch -p1 < "$OLDPWD/tools/sweetmtl/m0/mesa-a5xx-ir3.patch")
#   sh tools/sweetgl/mesa-setup.sh
# and the translator (tools/sweetmtl/m2v-fetch.sh; run here when tools/sweetmtl/m2v is missing). Needs cargo with
# the aarch64-apple-ios target, python3, and an LLVM 21+ llvm-as (LLVM_AS) for the fixtures.
#
# Output in OUT (default tools/sweetmtl/out/ios): mtlbridgetest and mtlabitest (stripped, signed with
# test/mtltool-ents.plist), the same unstripped as NAME.unstripped, and the build's intermediate files.
#
# M1 (plan 4.1, 4.4 step 3-4): also SweetMetal.bundle, the Metal plug-in (frontend/: SweetMetal.mm, the plug-in class
# SweetMTLDevice, + NativeBridgeMetalFrontend.mm over the same bridge and shim; executable SweetMetal, Info.plist,
# _CodeSignature, signed ad hoc), with SweetMetal.unstripped beside it, and mtltest (test/mtltest.m: Metal.framework's
# device through the plug-in; Apple's frameworks only).
set -euo pipefail
H=$(cd "$(dirname "$0")" && pwd)
P=$(cd "$H/../.." && pwd)
MESA_SRC=${MESA_SRC:-$P/research/mesa-mtl}
MESA_BUILD=${MESA_BUILD:-$P/research/mesa-ios-mtl}
OUT=${OUT:-$H/out/ios}
export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-$H/out/cargo}
export IPHONEOS_DEPLOYMENT_TARGET=16.0
export LLVM_AS=${LLVM_AS:-llvm-as}
SDK=$(xcrun --sdk iphoneos --show-sdk-path)
CC="$(xcrun --sdk iphoneos --find clang) -isysroot $SDK -arch arm64 -miphoneos-version-min=16.0"
mkdir -p "$OUT"

echo "== Mesa's static libraries ($MESA_BUILD)"
LIBS="src/gallium/drivers/freedreno/libfreedreno.a src/gallium/winsys/freedreno/drm/libfreedrenowinsys.a
	src/freedreno/drm/libfreedreno_drm.a src/freedreno/ir3/libfreedreno_ir3.a src/freedreno/ir2/libfreedreno_ir2.a
	src/freedreno/fdl/libfreedreno_layout.a src/freedreno/common/libfreedreno_common.a
	src/freedreno/perfcntrs/libfreedreno_perfcntrs.a src/freedreno/isa/libir3encode.a
	src/freedreno/isa/libir3decode.a src/compiler/isaspec/libisaspec.a src/gallium/auxiliary/libgallium.a
	src/compiler/spirv/libvtn.a src/compiler/nir/libnir.a src/compiler/libcompiler.a src/util/libxmlconfig.a
	src/util/libmesa_util.a src/util/libmesa_util_simd.a src/util/blake3/libblake3.a
	src/c11/impl/libmesa_util_c11.a"
# NINJA_FLAGS: e.g. "-k 0" to see every compile error in one run
(cd "$MESA_BUILD" && ninja ${NINJA_FLAGS:-} $LIBS)

echo "== Gallium shim and sweet_drm.c"
CC="$CC" AR="$(xcrun --sdk iphoneos --find ar)" \
	"$H/gallium/build-host.sh" "$MESA_SRC" "$MESA_BUILD" "$OUT/gallium" "$P/tools/sweetgl/sweet_drm.c"

echo "== runtime, bridge, translator (cargo, aarch64-apple-ios)"
[ -e "$H/m2v/crates/metal2vulkan/Cargo.toml" ] || sh "$H/m2v-fetch.sh"
(cd "$H/bridge" && cargo build --release --target aarch64-apple-ios)
BRIDGE=$CARGO_TARGET_DIR/aarch64-apple-ios/release/libnative_metal_bridge.a

echo "== mtlabitest's fixtures (embedded)"
F=$H/m2v/crates/metal2vulkan-validation/fixtures/public
mkdir -p "$OUT/air"
"$LLVM_AS" -o "$OUT/air/stage_io.air" "$F/engine/stage_io.ll"
"$LLVM_AS" -o "$OUT/air/sampling.air" "$F/engine/sampling.ll"
"$LLVM_AS" -o "$OUT/air/threadgroup_word.air" "$F/kernel_threadgroup_word.ll"
python3 -I - "$OUT/air" "$OUT/mtlabitest-air.h" <<'PY'
import os, sys
d, out = sys.argv[1], sys.argv[2]
names = ["stage_io.air", "sampling.air", "threadgroup_word.air"]
with open(out, "w") as f:
    f.write("/* generated by tools/sweetmtl/build-ios.sh: mtlabitest's fixtures, from metal2vulkan's */\n")
    f.write("#include <stddef.h>\n")
    for i, n in enumerate(names):
        b = open(os.path.join(d, n), "rb").read()
        f.write("static const unsigned char embedded_air_%d[%d] = {\n" % (i, len(b)))
        for j in range(0, len(b), 24):
            f.write("".join("%d," % x for x in b[j:j + 24]) + "\n")
        f.write("};\n")
    f.write("static const struct { const char *name; const unsigned char *bytes; size_t size; } embedded_air[] = {\n")
    for i, n in enumerate(names):
        f.write('\t{"%s", embedded_air_%d, sizeof(embedded_air_%d)},\n' % (n, i, i))
    f.write("};\n")
PY

echo "== link, strip, sign"
for t in mtlbridgetest mtlabitest; do
	EXTRA=
	if [ "$t" = mtlabitest ]; then
		EXTRA="-DMTLABITEST_EMBEDDED_AIR -include $OUT/mtlabitest-air.h"
	fi
	# ld64 searches every archive as often as needed: no link groups
	$CC -O2 -Wall $EXTRA -I "$H/bridge" -I "$H/test" -o "$OUT/$t.unstripped" "$H/test/$t.c" "$BRIDGE" \
		"$OUT/gallium/libsweetgallium.a" $(cat "$OUT/gallium/mesa-libs.txt") \
		-framework IOKit -framework CoreFoundation -framework IOSurface -lc++ -lz -Wl,-dead_strip
	cp "$OUT/$t.unstripped" "$OUT/$t"
	"$(xcrun --sdk iphoneos --find strip)" -x "$OUT/$t"
	codesign -f -s - --entitlements "$H/test/mtltool-ents.plist" "$OUT/$t"
	codesign -f -s - --entitlements "$H/test/mtltool-ents.plist" "$OUT/$t.unstripped"
done

echo "== SweetMetal.bundle (the Metal plug-in)"
CXX="$(xcrun --sdk iphoneos --find clang++) -isysroot $SDK -arch arm64 -miphoneos-version-min=16.0"
B=$OUT/SweetMetal.bundle
rm -rf "$B"
mkdir -p "$B"
# Nothing exported: Metal finds SweetMTLDevice through the Objective-C runtime (the class list), and -dead_strip may then
# drop every bridge call the frontend does not make.
printf '# none: Metal finds SweetMTLDevice through the Objective-C runtime\n' > "$OUT/SweetMetal-exports.txt"
# clang++ adds libc++ itself. _MTLDevice, the plug-in class's private superclass, is in the SDK's Metal.tbd.
$CXX -x objective-c++ -std=c++17 -fobjc-arc -O2 -Wall -Wno-deprecated-declarations -Wno-unused-function \
	-fvisibility=hidden -I "$H" -I "$H/frontend" -bundle -o "$OUT/SweetMetal.unstripped" \
	"$H/frontend/SweetMetal.mm" "$H/frontend/NativeBridgeMetalFrontend.mm" -x none "$BRIDGE" \
	"$OUT/gallium/libsweetgallium.a" $(cat "$OUT/gallium/mesa-libs.txt") \
	-framework Foundation -framework Metal -framework IOSurface -framework IOKit -framework CoreFoundation -lz \
	-Wl,-dead_strip -Wl,-exported_symbols_list,"$OUT/SweetMetal-exports.txt"
cp "$OUT/SweetMetal.unstripped" "$B/SweetMetal"
"$(xcrun --sdk iphoneos --find strip)" -x "$B/SweetMetal"
cp "$H/frontend/Info.plist" "$B/Info.plist"
plutil -lint "$B/Info.plist"
codesign -f -s - "$B"
codesign -f -s - "$OUT/SweetMetal.unstripped"
codesign -v "$B"
ls -la "$B" "$B/_CodeSignature"

echo "== mtltest"
$CC -x objective-c -fobjc-arc -O2 -Wall -I "$H/test" -o "$OUT/mtltest.unstripped" "$H/test/mtltest.m" \
	-framework Foundation -framework Metal -framework IOSurface -framework IOKit -framework CoreFoundation
cp "$OUT/mtltest.unstripped" "$OUT/mtltest"
"$(xcrun --sdk iphoneos --find strip)" -x "$OUT/mtltest"
codesign -f -s - --entitlements "$H/test/mtltool-ents.plist" "$OUT/mtltest"
codesign -f -s - --entitlements "$H/test/mtltool-ents.plist" "$OUT/mtltest.unstripped"

echo "== weak imports (iOS 16 lacks what newer SDKs declare: those resolve to NULL there, the strchrnul lesson)"
BAD=0
for t in mtlbridgetest mtlabitest SweetMetal.bundle/SweetMetal mtltest; do
	WEAK=$(nm -m "$OUT/$t" | grep "weak external" | grep -v "dynamically looked up" || true)
	IMPORTS=$(printf '%s\n' "$WEAK" | grep "(undefined)" || true)
	echo "$t: $(printf '%s' "$WEAK" | grep -c . || true) weak external symbols," \
		"$(printf '%s' "$IMPORTS" | grep -c . || true) of them weak imports"
	if [ -n "$IMPORTS" ]; then
		printf '%s\n' "$IMPORTS"
		BAD=1
	fi
done
[ "$BAD" = 0 ] || { echo "weak imports above: a symbol newer than iOS 16.0"; exit 1; }
echo "== the plug-in's superclass: _MTLDevice from Metal, nothing looked up in the flat namespace"
nm -m "$B/SweetMetal" | grep -F '_OBJC_CLASS_$__MTLDevice'
nm -m "$B/SweetMetal" | grep -F '_OBJC_CLASS_$__MTLDevice' | grep -q "(from Metal)" ||
	{ echo "SweetMetal does not take _MTLDevice from Metal"; exit 1; }
if nm -m "$B/SweetMetal" | grep "dynamically looked up"; then
	echo "SweetMetal looks the symbols above up at load"
	exit 1
fi
ls -la "$OUT/mtlbridgetest" "$OUT/mtlabitest" "$B/SweetMetal" "$OUT/mtltest"
